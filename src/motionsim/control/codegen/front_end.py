"""The front end's controller as C, and its replay.

The C is the controller of `control/front_end.py` line for line, with the gains tuned for the
design written in as constants. The replay feeds it the samples the simulation's controller was
given and holds its duty cycles to the simulation's: in double precision to rounding, in single
to half a percent of full scale.
"""

from __future__ import annotations

import json
import math
import subprocess
import tempfile
from pathlib import Path

from motionsim.control.codegen.replay import compiler
from motionsim.control.front_end import MOST_DUTY, TWO_PI, Controller, Gains, Linked

HEADER = "motionsim_front_end.h"
SOURCE = "motionsim_front_end.c"
HARNESS = "front_end_replay.c"
DATA = "front_end_replay_data.txt"
STRESS = "front_end_replay_limits.txt"
# Single precision is held to half a percent of full scale: where the duty cycle meets its limit
# at the mains' zero crossings, a float's rounding decides a sample sooner or later whether the
# integrator holds, and the two runs part by a thousandth or so until the loop pulls them together.
TOLERANCE = {"double": 1e-9, "float": 5e-3}
# Past its limits, with no stage behind it to pull the two runs together, single precision is held
# to two percent: the limits and both anti-windups are still the simulation's, as double shows.
PAST_LIMITS = {"double": 1e-9, "float": 2e-2}
SECONDS = 60


def _c(value: float) -> str:
    """A figure as C reads it back to the last bit."""
    text = f"{value:.17g}"
    return text if any(ch in text for ch in ".en") else text + ".0"


def header(g: Gains) -> str:
    fast = (
        "/* Every sample: the boost switch's duty cycle, from the rectified mains voltage (V),\n"
        "   the inductor's current (A) and the link's voltage (V). */\n"
        "fe_real fe_fast(fe_state *s, fe_real v_in, fe_real i_l, fe_real v_dc);\n"
        if g.phases == 1
        else "/* Every sample: each leg's duty cycle, from the mains voltages to neutral (V), the line\n"
        "   currents into the stage (A) and the link's voltage (V). */\n"
        "void fe_fast3(fe_state *s, const fe_real e[3], const fe_real i[3], fe_real v_dc, fe_real duty[3]);\n"
    )
    return (
        "/* The front end's controller: generated by MotionSim for one design. */\n"
        "#ifndef MOTIONSIM_FRONT_END_H\n#define MOTIONSIM_FRONT_END_H\n\n"
        "#ifndef FE_REAL\n#define FE_REAL double\n#endif\ntypedef FE_REAL fe_real;\n\n"
        f"/* The fast loop's period, s, and how many of them make one of the slow loop's. */\n"
        f"#define FE_TS {_c(g.ts)}\n#define FE_SLOW_EVERY {g.slow}\n\n"
        "typedef struct {\n"
        "  fe_real x1, x2; /* the notch's state */\n"
        "  fe_real xv;     /* the link loop's integrator, W */\n"
        "  fe_real p;      /* the power asked of the mains, W */\n"
        "  fe_real ms;     /* the mains voltage's mean square */\n"
        "  fe_real xi;     /* the current loop's integrator (one phase) */\n"
        "  fe_real theta, w, xw, xd, xq, ed; /* three phases: the mains' angle and the two axes */\n"
        "} fe_state;\n\n"
        "/* Start as a stage that has been holding the link at v_dc with p drawn from it. */\n"
        "void fe_settle(fe_state *s, fe_real v_dc, fe_real p);\n"
        "/* Once every FE_SLOW_EVERY samples, before the fast loop: the link's loop. p_ff is the power\n"
        "   the motor's control is about to draw from the link, W. Returns the power asked of the mains. */\n"
        "fe_real fe_slow(fe_state *s, fe_real v_dc, fe_real p_ff);\n" + fast + "\n#endif\n"
    )


def _defines(g: Gains, v_peak: float) -> str:
    rows = [(name.upper(), value) for name, value in g.figures().items() if name not in ("ts", "slow", "feed_forward")]
    rows += [("MOST_DUTY", MOST_DUTY), ("V_PEAK", v_peak)]
    lines = [f"#define FE_{name} ((fe_real){_c(value)})" for name, value in rows]
    lines.append(f"#define FE_FEED_FORWARD {1 if g.feed_forward else 0}")
    lines.append(f"#define FE_RETURNS {1 if g.p_min < 0 else 0}")
    return "\n".join(lines)


_COMMON = """
static fe_real fe_clamp(fe_real x, fe_real lo, fe_real hi) { return x < lo ? lo : (x > hi ? hi : x); }

void fe_settle(fe_state *s, fe_real v_dc, fe_real p) {
  s->x1 = v_dc * ((fe_real)1.0 - FE_B0);
  s->x2 = v_dc * (FE_B2 - FE_A2);
  s->xv = FE_FEED_FORWARD ? (fe_real)0.0 : p;
  s->p = p;
  s->ms = (fe_real)0.5 * FE_V_PEAK * FE_V_PEAK;
  s->xi = (fe_real)0.0;
  s->theta = (fe_real)0.0;
  s->w = FE_W0;
  s->xw = s->xd = s->xq = (fe_real)0.0;
  s->ed = FE_V_PEAK;
}

fe_real fe_slow(fe_state *s, fe_real v_dc, fe_real p_ff) {
  fe_real y = FE_B0 * v_dc + s->x1;
  fe_real e, p, p_sat;
  s->x1 = FE_B1 * v_dc - FE_A1 * y + s->x2;
  s->x2 = FE_B2 * v_dc - FE_A2 * y;
  e = FE_V_REF - y;
  p = FE_KP_V * e + s->xv;
  if (FE_FEED_FORWARD) p = p + p_ff;
  p_sat = fe_clamp(p, FE_P_MIN, FE_P_MAX);
  /* The integrator stops where the power asked for is at its limit and it would push further. */
  if (p == p_sat || ((p > p_sat) != (e > (fe_real)0.0))) s->xv = s->xv + FE_KI_V * e;
  s->p = p_sat;
  return p_sat;
}
"""

_ONE = """
fe_real fe_fast(fe_state *s, fe_real v_in, fe_real i_l, fe_real v_dc) {
  fe_real i_ref, e, u, d, d_sat;
  s->ms = s->ms + FE_A_MS * (v_in * v_in - s->ms);
  i_ref = s->p / s->ms * v_in;
  i_ref = fe_clamp(i_ref, FE_RETURNS ? -FE_I_MAX : (fe_real)0.0, FE_I_MAX);
  e = i_ref - i_l;
  u = FE_KP_I * e + s->xi;
  d = (fe_real)1.0 - (v_in - u) / v_dc;
  /* A stage with a diode keeps it its turn; one with a switch in its place needs none. */
  d_sat = fe_clamp(d, (fe_real)0.0, FE_RETURNS ? (fe_real)1.0 : FE_MOST_DUTY);
  if (d == d_sat) s->xi = s->xi + FE_KI_I * e;
  return d_sat;
}
"""

_THREE = """
#define FE_SQRT3 ((fe_real)1.7320508075688772)
#define FE_TWO_PI ((fe_real)6.2831853071795862)

static fe_real fe_max3(fe_real a, fe_real b, fe_real c) { fe_real m = a > b ? a : b; return m > c ? m : c; }
static fe_real fe_min3(fe_real a, fe_real b, fe_real c) { fe_real m = a < b ? a : b; return m < c ? m : c; }

void fe_fast3(fe_state *s, const fe_real e[3], const fe_real i[3], fe_real v_dc, fe_real duty[3]) {
  fe_real e_al = ((fe_real)2.0 * e[0] - e[1] - e[2]) / (fe_real)3.0;
  fe_real e_be = (e[1] - e[2]) / FE_SQRT3;
  fe_real i_al = ((fe_real)2.0 * i[0] - i[1] - i[2]) / (fe_real)3.0;
  fe_real i_be = (i[1] - i[2]) / FE_SQRT3;
  fe_real c = (fe_real)cos((double)s->theta), sn = (fe_real)sin((double)s->theta);
  fe_real e_d = c * e_al + sn * e_be;
  fe_real e_q = -sn * e_al + c * e_be;
  fe_real i_d = c * i_al + sn * i_be;
  fe_real i_q = -sn * i_al + c * i_be;
  fe_real floor_ed, lock, id_ref, err_d, err_q, wl, v_d, v_q, v_al, v_be, va, vb, vc, mid, da, db, dc, sa, sb, sc;
  /* The loop that follows the mains' angle: the voltage has no part across it once locked. */
  s->ed = s->ed + (fe_real)0.01 * (e_d - s->ed);
  floor_ed = s->ed > (fe_real)1.0 ? s->ed : (fe_real)1.0;
  lock = e_q / floor_ed;
  s->w = FE_W0 + FE_KP_PLL * lock + s->xw;
  s->xw = s->xw + FE_KI_PLL * lock;
  id_ref = s->p / ((fe_real)1.5 * floor_ed);
  id_ref = fe_clamp(id_ref, FE_RETURNS ? -FE_I_MAX : (fe_real)0.0, FE_I_MAX);
  err_d = id_ref - i_d;
  err_q = -i_q;
  wl = s->w * FE_INDUCTANCE;
  v_d = e_d - (FE_KP_I * err_d + s->xd) + wl * i_q;
  v_q = e_q - (FE_KP_I * err_q + s->xq) - wl * i_d;
  v_al = c * v_d - sn * v_q;
  v_be = sn * v_d + c * v_q;
  va = v_al;
  vb = (fe_real)-0.5 * v_al + (fe_real)0.5 * FE_SQRT3 * v_be;
  vc = (fe_real)-0.5 * v_al - (fe_real)0.5 * FE_SQRT3 * v_be;
  /* Centred between the rails: the room of space-vector modulation. */
  mid = (fe_real)-0.5 * (fe_max3(va, vb, vc) + fe_min3(va, vb, vc));
  da = (fe_real)0.5 + (va + mid) / v_dc;
  db = (fe_real)0.5 + (vb + mid) / v_dc;
  dc = (fe_real)0.5 + (vc + mid) / v_dc;
  sa = fe_clamp(da, (fe_real)0.0, (fe_real)1.0);
  sb = fe_clamp(db, (fe_real)0.0, (fe_real)1.0);
  sc = fe_clamp(dc, (fe_real)0.0, (fe_real)1.0);
  if (sa == da && sb == db && sc == dc) {
    s->xd = s->xd + FE_KI_I * err_d;
    s->xq = s->xq + FE_KI_I * err_q;
  }
  s->theta = s->theta + s->w * (fe_real)FE_TS;
  if (s->theta > FE_TWO_PI) s->theta = s->theta - FE_TWO_PI;
  duty[0] = sa; duty[1] = sb; duty[2] = sc;
}
"""


def source(g: Gains, v_peak: float, lines: list[str]) -> str:
    about = "\n".join(f" * {line}" for line in lines)
    return (
        f"/* The front end's controller, generated by MotionSim.\n{about}\n */\n"
        f'#include "{HEADER}"\n#include <math.h>\n\n{_defines(g, v_peak)}\n{_COMMON}'
        + (_ONE if g.phases == 1 else _THREE)
    )


def harness(g: Gains) -> str:
    """The replay: every recorded sample given to the C, the power it asks for and its duty
    cycles held to the recorded ones. A figure that is not a number fails it, and so does a
    file with fewer samples than it says it has."""
    n_in, n_out = (2, 1) if g.phases == 1 else (6, 3)
    step = (
        "    out[0] = (double)fe_fast(&s, (fe_real)in[0], (fe_real)in[1], (fe_real)v_dc);\n"
        if g.phases == 1
        else "    { fe_real e[3], i[3], d[3]; int j;\n"
        "      for (j = 0; j < 3; j++) { e[j] = (fe_real)in[j]; i[j] = (fe_real)in[3 + j]; }\n"
        "      fe_fast3(&s, e, i, (fe_real)v_dc, d);\n"
        "      for (j = 0; j < 3; j++) out[j] = (double)d[j]; }\n"
    )
    return (
        f'#include "{HEADER}"\n#include <math.h>\n#include <stdio.h>\n#include <stdlib.h>\n\n'
        f"#define N_IN {n_in}\n#define N_OUT {n_out}\n\n"
        "int main(int argc, char **argv) {\n"
        "  FILE *f; double tolerance, v0, p0, p_scale, worst = 0.0; long n = 0, rows = 0; int bad = 0; fe_state s;\n"
        "  if (argc < 3) return 2;\n"
        '  f = fopen(argv[1], "r"); if (!f) return 2;\n'
        "  tolerance = atof(argv[2]);\n"
        "  /* rows, the settled link and power, and the power the asked power is a share of */\n"
        '  if (fscanf(f, "%ld %lf %lf %lf", &rows, &v0, &p0, &p_scale) != 4) return 2;\n'
        "  fe_settle(&s, (fe_real)v0, (fe_real)p0);\n"
        "  for (;;) {\n"
        "    int slow, j; double v_dc, p_ff, p_want, off, in[N_IN], want[N_OUT], out[N_OUT];\n"
        '    if (fscanf(f, "%d %lf %lf %lf", &slow, &v_dc, &p_ff, &p_want) != 4) break;\n'
        '    for (j = 0; j < N_IN; j++) if (fscanf(f, "%lf", &in[j]) != 1) return 2;\n'
        '    for (j = 0; j < N_OUT; j++) if (fscanf(f, "%lf", &want[j]) != 1) return 2;\n'
        "    if (slow) {\n"
        "      off = fabs((double)fe_slow(&s, (fe_real)v_dc, (fe_real)p_ff) - p_want) / p_scale;\n"
        "      if (!(off <= tolerance)) bad = 1;\n"
        "      if (off > worst) worst = off;\n"
        "    }\n" + step + "    for (j = 0; j < N_OUT; j++) {\n"
        "      off = fabs(out[j] - want[j]);\n"
        "      if (!(off <= tolerance)) bad = 1;\n"
        "      if (off > worst) worst = off;\n"
        "    }\n"
        "    n++;\n"
        "  }\n"
        "  fclose(f);\n"
        "  if (n != rows || n == 0) bad = 1;\n"
        '  printf("{\\"passed\\": %s, \\"samples\\": %ld, \\"rows\\": %ld, \\"worst\\": %.3g, \\"tolerance\\": %.0e}\\n",\n'
        '         bad ? "false" : "true", n, rows, worst, tolerance);\n'
        "  return bad ? 1 : 0;\n"
        "}\n"
    )


def _rows(kept: dict, v0: float, p0: float, p_scale: float) -> str:
    """Recorded samples as the harness reads them: a first line of the count, the settled link
    and power and the power's scale; then a line a sample: whether the slow loop ran, the link's
    voltage, the feed forward, the power asked for, the fast loop's inputs, its duty cycles."""
    rows = [f"{len(kept['slow'])} {v0!r} {p0!r} {p_scale!r}"]
    for k in range(len(kept["slow"])):
        figures = [kept["v_dc"][k], kept["p_ff"][k], kept["p"][k], *kept["in"][k], *kept["out"][k]]
        rows.append(f"{kept['slow'][k]} " + " ".join(repr(float(x)) for x in figures))
    return "\n".join(rows) + "\n"


def stressed(g: Gains, v_peak: float, samples: int = 6000) -> dict:
    """The controller driven past its limits with no stage behind it, for the replay: a feed
    forward past the most power and under the least, a link far off its set point, a current
    that does not follow. What a quiet test never reaches (the limits, both anti-windups) is
    reached here, and the C is held to it."""
    ctl = Controller(g, v_peak)
    ctl.settle(g.v_ref, 0.3 * g.p_max)
    kept: dict[str, list] = {"v_dc": [], "p_ff": [], "slow": [], "in": [], "out": [], "p": []}
    third = samples // 3
    for k in range(samples):
        angle = g.w0 * k * g.ts
        stretch = k // third
        # A third each: far past the most power on a low link; braking on a high one; back.
        p_ff = (2.5 * g.p_max, -2.5 * g.p_max, 0.4 * g.p_max)[min(stretch, 2)]
        v_dc = g.v_ref * (0.8, 1.2, 1.0)[min(stretch, 2)] + 5.0 * math.sin(2.0 * angle)
        slow = k % g.slow == 0
        if slow:
            ctl.slow(v_dc, p_ff)
        kept["slow"].append(1 if slow else 0)
        kept["v_dc"].append(v_dc)
        kept["p_ff"].append(p_ff)
        kept["p"].append(ctl.p)
        # A current that lags what is asked and swings past the limit either way.
        amps = 1.3 * g.i_max * math.sin(angle - 0.6)
        if g.phases == 1:
            v_in = v_peak * abs(math.sin(angle))
            i_l = abs(amps) if g.p_min >= 0.0 else amps
            kept["in"].append((v_in, i_l))
            kept["out"].append((ctl.fast(v_in, i_l, v_dc),))
        else:
            shifts = (0.0, -TWO_PI / 3.0, TWO_PI / 3.0)
            ea, eb, ec = (v_peak * math.sin(angle + x) for x in shifts)
            ia, ib, ic = (1.3 * g.i_max * math.sin(angle - 0.6 + x) for x in shifts)
            e, i = (ea, eb, ec), (ia, ib, ic)
            kept["in"].append((*e, *i))
            kept["out"].append(ctl.fast3(e, i, v_dc))
    return kept


def files(g: Gains, v_peak: float, through: Linked, v0: float, p0: float, lines: list[str]) -> dict[str, str]:
    """The front end's part of a bundle: relative path -> text."""
    return {
        f"front_end/{HEADER}": header(g),
        f"front_end/{SOURCE}": source(g, v_peak, lines),
        f"front_end/{HARNESS}": harness(g),
        f"front_end/{DATA}": _rows(through.recorded, v0, p0, g.p_max),
        f"front_end/{STRESS}": _rows(stressed(g, v_peak), g.v_ref, 0.3 * g.p_max, g.p_max),
    }


def _once(built: Path, data: Path, tolerance: float) -> dict:
    try:
        done = subprocess.run(
            [str(built), str(data), repr(tolerance)], capture_output=True, text=True, timeout=SECONDS, check=False
        )
    except subprocess.TimeoutExpired:
        return {"passed": False, "said": "did not finish"}
    try:
        return json.loads(done.stdout)
    except ValueError:
        return {"passed": False, "said": (done.stderr or done.stdout)[:2000]}


def replay(files_at: dict[str, str]) -> dict:
    """Compile the front end's controller with its harness in both precisions and run each on
    the run's samples and on the samples past its limits. Skipped, with the reason, where the
    host has no C compiler."""
    cc = compiler()
    if cc is None:
        return {
            "ran": False,
            "passed": None,
            "said": "no C compiler on this machine: the front end's replay was not run",
        }
    out: dict = {"ran": True, "precisions": {}}
    with tempfile.TemporaryDirectory(prefix="motionsim-front-end-") as where:
        root = Path(where)
        for name, text in files_at.items():
            if name.startswith("front_end/"):
                (root / Path(name).name).write_text(text, encoding="utf-8")
        for precision, tolerance in TOLERANCE.items():
            built = root / f"replay_{precision}"
            command = [*cc.split(), "-std=c99", "-O1", "-Wall", "-Wextra", "-Werror", f"-DFE_REAL={precision}"]
            command += [str(root / SOURCE), str(root / HARNESS), "-o", str(built), "-lm"]
            try:
                made = subprocess.run(command, capture_output=True, text=True, timeout=SECONDS, check=False)
            except subprocess.TimeoutExpired:
                out["precisions"][precision] = {"compiled": False, "passed": False, "said": "did not finish compiling"}
                continue
            if made.returncode != 0:
                out["precisions"][precision] = {"compiled": False, "passed": False, "said": made.stderr[:2000]}
                continue
            run, limits = _once(built, root / DATA, tolerance), _once(built, root / STRESS, PAST_LIMITS[precision])
            out["precisions"][precision] = {
                "compiled": True,
                "passed": bool(run.get("passed") and limits.get("passed")),
                "samples": run.get("samples", 0),
                "worst": run.get("worst"),
                "tolerance": tolerance,
                "limits": limits,
            }
    out["passed"] = all(p.get("passed") for p in out["precisions"].values())
    parts = []
    for precision, found in out["precisions"].items():
        if not found.get("compiled"):
            parts.append(f"{precision}: did not compile")
            continue
        verdict = "passed" if found["passed"] else "FAILED"
        limits = found["limits"]
        parts.append(
            f"{precision}: {verdict}, {found['samples']} samples of the run within {found['worst']:.3g}"
            f" and {limits.get('samples', 0)} past its limits within {limits.get('worst', float('nan')):.3g}"
            f" (tolerance {found['tolerance']:.0e})"
            if found["worst"] is not None
            else f"{precision}: {verdict}"
        )
    out["said"] = "; ".join(parts)
    return out
